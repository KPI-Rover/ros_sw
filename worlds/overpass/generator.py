"""
Overpass world generator: scatters objects over the free area of the
warehouse, off the overpass and the start points, and off the figure eight
too unless objects_on_route is true (then they are obstacles on it); makes
the textured meshes of the warehouse walls and, for a 'road' surface, the
road band along the figure eight. The launch file calls prepare() before
processing overpass.sdf.xacro.

It can also be run directly to print a placement:
    python3 generator.py --objects 16 --objects-seed 3
"""

import argparse
import hashlib
import math
import os
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
INCLUDE_DIR = os.path.join(HERE, '..', 'include')
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib'))
import scatter  # noqa: E402
import textured_box  # noqa: E402

# Free space kept on each side of the lane and around the overpass and start points, m.
LANE_MARGIN = 0.35
START_RADIUS = 0.6
# Road band: height above the floor (under the marking lines, 1 mm thick) and arc segment length, m.
ROAD_HEIGHT = 0.0005
ROAD_STEP = 0.1


def load_params():
    with open(os.path.join(HERE, 'params.yaml')) as f:
        return yaml.safe_load(f)


def figure_eight(p):
    """The figure eight on the floor: ('arc', cx, cy, r, a1, a2) and ('segment', x1, y1, x2, y2) pieces."""
    r, lt = p['loop_radius'], p['tangent_distance']
    d, alpha = math.hypot(lt, r), math.atan2(r, lt)
    ca, sa = math.cos(alpha), math.sin(alpha)
    foot = p['deck_length'] / 2 + p['height'] * math.pi / (2 * math.tan(math.radians(p['max_slope'])))
    return [('arc', d, 0, r, -(math.pi / 2 + alpha), math.pi / 2 + alpha),
            ('arc', -d, 0, r, math.pi / 2 - alpha, 3 * math.pi / 2 + alpha),
            ('segment', -lt * ca, lt * sa, lt * ca, -lt * sa),
            ('segment', -lt * ca, -lt * sa, -foot * ca, -foot * sa),
            ('segment', foot * ca, foot * sa, lt * ca, lt * sa)]


def road_mesh(p, width, tile):
    """
    OBJ path of the road band along the figure eight on the floor, 'width'
    wide, with texture coordinates in units of 'tile' m; cached by its shape.
    """
    name = 'road_' + hashlib.sha1(repr((sorted(p.items(), key=str), width, tile)).encode()).hexdigest()[:12] + '.obj'
    path = os.path.join(textured_box.CACHE_DIR, name)
    if os.path.isfile(path):
        return path
    lines, faces, n = ['# Overpass road band, generated by overpass/generator.py'], [], 0
    for piece in figure_eight(p):
        if piece[0] == 'arc':
            _, cx, cy, r, a1, a2 = piece
            k = max(2, int(abs(a2 - a1) * r / ROAD_STEP) + 1)
            points = [(cx + r * math.cos(a1 + (a2 - a1) * i / (k - 1)), cy + r * math.sin(a1 + (a2 - a1) * i / (k - 1)))
                      for i in range(k)]
        else:
            _, x1, y1, x2, y2 = piece
            points = [(x1, y1), (x2, y2)]
        along = 0.0
        for i, (x, y) in enumerate(points):
            ax, ay = points[min(i + 1, len(points) - 1)]
            bx, by = points[max(i - 1, 0)]
            dx, dy = ax - bx, ay - by
            length = math.hypot(dx, dy)
            nx, ny = -dy / length * width / 2, dx / length * width / 2
            if i:
                along += math.hypot(x - points[i - 1][0], y - points[i - 1][1])
            for side in (-1, 1):
                lines.append(f'v {x + side * nx:.4f} {y + side * ny:.4f} {ROAD_HEIGHT}')
                lines.append(f'vt {along / tile:.4f} {(side + 1) / 2 * width / tile:.4f}')
            if i:
                # 1-based vertices: right and left of the previous point, right and left of this one; counterclockwise from above.
                a, b, c, e = n + 2 * i - 1, n + 2 * i, n + 2 * i + 1, n + 2 * i + 2
                faces.append(f'f {a}/{a}/1 {c}/{c}/1 {e}/{e}/1 {b}/{b}/1')
        n += 2 * len(points)
    lines.append('vn 0 0 1')
    os.makedirs(textured_box.CACHE_DIR, exist_ok=True)
    with open(path + '.tmp', 'w') as f:
        f.write('\n'.join(lines + faces) + '\n')
    os.replace(path + '.tmp', path)
    return path


def shapes(overpass_type, objects_on_route=False):
    """
    Scatter area, keep-out shapes and obstacles of the overpass world (see
    overpass.sdf.xacro); with objects_on_route the figure eight is not kept free.
    """
    p = load_params()
    cfg = p['overpass_types'][overpass_type]
    r, lt = p['loop_radius'], p['tangent_distance']
    d, alpha = math.hypot(lt, r), math.atan2(r, lt)
    ca, sa = math.cos(alpha), math.sin(alpha)
    foot = p['deck_length'] / 2 + p['height'] * math.pi / (2 * math.tan(math.radians(p['max_slope'])))
    lane = max(cfg['width'], 0.5) / 2 + LANE_MARGIN
    overpass = ('segment', -foot * ca, -foot * sa, foot * ca, foot * sa, cfg['width'] / 2)

    route = [
        ('arc', d, 0, r, -(math.pi / 2 + alpha), math.pi / 2 + alpha, lane),
        ('arc', -d, 0, r, math.pi / 2 - alpha, 3 * math.pi / 2 + alpha, lane),
        ('segment', -lt * ca, lt * sa, lt * ca, -lt * sa, lane),
        ('segment', -lt * ca, -lt * sa, lt * ca, lt * sa, lane),
    ]
    # On the route, objects are obstacles; the overpass diagonal (its ramps) and the start points stay free anyway.
    keep_out = [route[3]] if objects_on_route else route
    keep_out += [('circle', d + r, 0, START_RADIUS), ('circle', -(d + r), 0, START_RADIUS)]
    area = (-p['size_x'] / 2, p['size_x'] / 2, -p['size_y'] / 2, p['size_y'] / 2)
    return area, keep_out, [overpass]


def prepare(args):
    """Launch hook: scatter objects and return the xacro mappings with 'layout' set to a temporary file."""
    if args.get('layout'):
        return args
    on_route = str(args.get('objects_on_route', 'false')).lower() in ('true', '1')
    area, keep_out, obstacles = shapes(args['overpass'], on_route)
    objects = scatter.scatter_from_args(args, area, keep_out, obstacles, 'overpass')
    p = load_params()
    with open(os.path.join(INCLUDE_DIR, 'walls.yaml')) as f:
        walls_cfg = yaml.safe_load(f)
    layout = dict(objects=objects, meshes=textured_box.wall_meshes(
        textured_box.perimeter_boxes(p['size_x'], p['size_y']), args.get('wall_material', 'plain'), walls_cfg))
    road = args.get('road', 'none')
    if road != 'none':
        with open(os.path.join(INCLUDE_DIR, 'floors.yaml')) as f:
            floor = yaml.safe_load(f)[road]
        layout['road'] = dict(mesh=road_mesh(p, p['overpass_types'][args['overpass']]['width'], floor['tile']),
                              surface=road)
    with tempfile.NamedTemporaryFile('w', prefix='kpi_rover_overpass_', suffix='.yaml', delete=False) as f:
        yaml.safe_dump(layout, f, default_flow_style=None)
    return dict(args, layout=f.name)


def main():
    parser = argparse.ArgumentParser(description='Print a random object placement for the overpass world.')
    parser.add_argument('--objects', type=int, default=14)
    parser.add_argument('--objects-seed', default='')
    parser.add_argument('--overpass', default='wide')
    args = parser.parse_args()
    area, keep_out, obstacles = shapes(args.overpass)
    for obj in scatter.scatter_from_args(vars(args), area, keep_out, obstacles, 'overpass'):
        print(obj)


if __name__ == '__main__':
    main()
