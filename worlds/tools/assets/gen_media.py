"""
Generate media for worlds: stripe textures for markings, meshes for mitered
marking line corners and overpass meshes. Photo textures for floors and walls
are downloaded by fetch_textures.py.

Marking textures cover one stripe segment, which is 4 line widths long, and
are repeated along the line. Their '_tile' variants cover
one stripe period, 1 line width long, for short segments on curved surfaces.

Miter meshes are right triangles that fill a 45 degree cut at a 90 degree
corner of a marking line (see marking.xacro). They are 1 line width in size,
scaled to the actual width in the world, and their UVs continue the texture
of the adjacent line segment.

Traffic cone meshes (a square base and a cone body) use one texture: an
orange body with white bands and a black base, for the object library
(include/objects.yaml).

Overpass meshes are overpass bodies (two ramps with a smooth cosine profile
and a deck between them) in meters, one per size in OVERPASSES, used by the
overpass' macro in structures.xacro. Their UVs are in TEXTURE_TILE units, so
floor textures cover them at about the same scale as the floor.

Usage:
    python3 gen_media.py
"""

import math
import os
import numpy as np
from PIL import Image

MARKING_SIZE = (64, 256)


def stripes(color_a, color_b):
    """Diagonal stripes seamless along the line (texture V axis, which runs along a box length)."""
    w, h = MARKING_SIZE
    period = w
    y, x = np.mgrid[0:h, 0:w]
    is_a = ((x + y) % period) < period // 2
    rgb = np.where(is_a[..., None], np.array(color_a), np.array(color_b))
    return Image.fromarray((rgb * 255).astype(np.uint8))


YELLOW = (1.0, 0.8, 0.0)
BLACK = (0.05, 0.05, 0.05)
RED = (0.85, 0.05, 0.05)
WHITE = (0.95, 0.95, 0.95)

ORANGE = (1.0, 0.33, 0.03)
CONE_TEXTURE_SIZE = (128, 512)
CONE_BASE_V = 0.9   # texture V below which the cone body is, the base is above


def cone_texture():
    """Traffic cone texture: body along V from the bottom (V = 0.9) to the top (V = 0), base below V = 0.9."""
    w, h = CONE_TEXTURE_SIZE
    rgb = np.empty((h, w, 3))
    rgb[:] = ORANGE
    height = 1 - np.arange(h) / (h * CONE_BASE_V)    # body height fraction for each row
    for low, high in ((0.42, 0.55), (0.65, 0.75)):
        rgb[(height >= low) & (height <= high)] = WHITE
    rgb[np.arange(h) >= h * CONE_BASE_V] = BLACK
    return Image.fromarray((rgb * 255).astype(np.uint8))


TEXTURES = {
    'traffic_cone.png': cone_texture,
    'marking_yellow_black.png': lambda: stripes(YELLOW, BLACK),
    'marking_red_white.png': lambda: stripes(RED, WHITE),
    'marking_black_white.png': lambda: stripes(BLACK, WHITE),
}


# Miter triangles in line-local coordinates (in line widths): X along the line,
# Y to the left, top face at Z = 1 (scaled to the line thickness). 'end' meshes
# lie after the line end (X in [0, 1]), 'start' meshes before the line start
# (X in [-1, 0]). 'left'/'right' is the direction of the turn at the corner.
MITERS = {
    'miter_end_left.obj': [(0, -0.5), (1, -0.5), (0, 0.5)],
    'miter_end_right.obj': [(0, -0.5), (1, 0.5), (0, 0.5)],
    'miter_start_left.obj': [(-1, -0.5), (0, -0.5), (0, 0.5)],
    'miter_start_right.obj': [(-1, 0.5), (0, -0.5), (0, 0.5)],
}


def miter_uv(name, x, y):
    """
    UV continuing the texture of a line segment.

    On the top face of a box the texture is mapped as u = 0.5 - y / width and
    v = 0.5 - x / length, so V runs from 1 at the segment start to 0 at its end.
    A segment is about 4 widths long, so one width is 1/4 of V. The stripe
    texture repeats 4 times along V, so V values 0 and 1 are equivalent and
    'end' meshes continue from V = 1 while 'start' meshes continue from V = 0.
    OBJ V axis points up the image, hence the 1 - v.
    """
    u = 0.5 - y
    v = 1 - x / 4 if name.startswith('miter_end') else -x / 4
    return u, 1 - v


def write_miter(path, name, points):
    lines = ['# Marking line miter, generated by gen_media.py']
    lines += [f'v {x} {y} 1' for x, y in points]
    lines += ['vt {} {}'.format(*miter_uv(name, x, y)) for x, y in points]
    lines += ['vn 0 0 1', 'f 1/1/1 2/2/1 3/3/1']
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


# Overpass sizes used in worlds; the 'overpass' macro (structures.xacro) loads
# the mesh named by overpass_mesh_name() for its parameters.
OVERPASSES = [
    dict(width=0.7, height=0.45, deck_length=1.4, deck_thickness=0.05, max_slope=12),
    dict(width=0.4, height=0.45, deck_length=1.4, deck_thickness=0.05, max_slope=12),
]
RAMP_SEGMENTS = 48
# Size of the area covered by one floor texture, about the 'tile' in floors.yaml.
TEXTURE_TILE = 2.0


def overpass_mesh_name(width, height, deck_length, deck_thickness, max_slope):
    return f'overpass_w{width:g}_h{height:g}_d{deck_length:g}_t{deck_thickness:g}_s{max_slope:g}.obj'


def write_overpass(path, width, height, deck_length, deck_thickness, max_slope):
    """
    Overpass body along X centered at the origin: ramps rise from the ground at
    X = -+foot to the deck at X = -+deck_length / 2 with a cosine profile, which
    has its steepest slope (max_slope) in the middle and is flat at both ends.
    Ramps are solid down to the ground, the deck is 'deck_thickness' thick so
    there is room under it. UVs are in texture tiles: U across, V along the
    surface arc length.
    """
    ramp_length = height * math.pi / (2 * math.tan(math.radians(max_slope)))
    half = deck_length / 2
    foot = half + ramp_length

    def top(x):
        t = min(1.0, (foot - abs(x)) / ramp_length)
        return height * (1 - math.cos(math.pi * t)) / 2

    def top_normal(x):
        if abs(x) <= half:
            return (0, 0, 1)
        t = (foot - abs(x)) / ramp_length
        slope = height * math.pi * math.sin(math.pi * t) / (2 * ramp_length) * (1 if x < 0 else -1)
        length = math.hypot(slope, 1)
        return (-slope / length, 0, 1 / length)

    def bottom(x):
        return height - deck_thickness if abs(x) < half else 0

    ramp_xs = [-foot + ramp_length * i / RAMP_SEGMENTS for i in range(RAMP_SEGMENTS + 1)]
    xs = ramp_xs + [-x for x in reversed(ramp_xs)]
    arc = [0.0]
    for x0, x1 in zip(xs, xs[1:]):
        arc.append(arc[-1] + math.hypot(x1 - x0, top(x1) - top(x0)))
    y0, y1 = -width / 2, width / 2

    vertices, uvs, normals, faces = [], [], [], []

    def add_face(points, face_uvs, point_normals):
        first = len(vertices) + 1
        vertices.extend(points)
        uvs.extend(face_uvs)
        normals.extend(point_normals)
        faces.append(' '.join(f'{first + i}/{first + i}/{first + i}' for i in range(len(points))))

    tile = TEXTURE_TILE
    for i, (x0, x1) in enumerate(zip(xs, xs[1:])):
        z0, z1 = top(x0), top(x1)
        n0, n1 = top_normal(x0), top_normal(x1)
        v0, v1 = arc[i] / tile, arc[i + 1] / tile
        add_face([(x0, y0, z0), (x1, y0, z1), (x1, y1, z1), (x0, y1, z0)],
                 [(0, v0), (0, v1), (width / tile, v1), (width / tile, v0)], [n0, n1, n1, n0])
        # Sides and the bottom, using the column bottom at its middle (the deck is between ramp samples).
        b = bottom((x0 + x1) / 2)
        add_face([(x0, y0, b), (x1, y0, b), (x1, y0, z1), (x0, y0, z0)],
                 [(x0 / tile, b / tile), (x1 / tile, b / tile), (x1 / tile, z1 / tile), (x0 / tile, z0 / tile)], [(0, -1, 0)] * 4)
        add_face([(x0, y1, b), (x0, y1, z0), (x1, y1, z1), (x1, y1, b)],
                 [(x0 / tile, b / tile), (x0 / tile, z0 / tile), (x1 / tile, z1 / tile), (x1 / tile, b / tile)], [(0, 1, 0)] * 4)
        add_face([(x0, y0, b), (x0, y1, b), (x1, y1, b), (x1, y0, b)],
                 [(x0 / tile, y0 / tile), (x0 / tile, y1 / tile), (x1 / tile, y1 / tile), (x1 / tile, y0 / tile)], [(0, 0, -1)] * 4)

    # Ramp end faces under the deck, facing the room under it.
    low = height - deck_thickness
    for x, normal in ((-half, (1, 0, 0)), (half, (-1, 0, 0))):
        points = [(x, y0, 0), (x, y1, 0), (x, y1, low), (x, y0, low)]
        if normal[0] < 0:
            points.reverse()
        add_face(points, [(p[1] / tile, p[2] / tile) for p in points], [normal] * 4)

    lines = ['# Overpass body, generated by gen_media.py']
    lines += ['v {:.6f} {:.6f} {:.6f}'.format(*v) for v in vertices]
    lines += ['vt {:.6f} {:.6f}'.format(*t) for t in uvs]
    lines += ['vn {:.6f} {:.6f} {:.6f}'.format(*n) for n in normals]
    lines += ['f ' + f for f in faces]
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


# Traffic cone sizes: height, base side, bottom and top body radius, m.
CONES = {
    'traffic_cone_45.obj': (0.45, 0.34, 0.13, 0.025),
    'traffic_cone_30.obj': (0.30, 0.24, 0.09, 0.018),
}
CONE_BASE_HEIGHT = 0.03
CONE_SEGMENTS = 32


def write_cone(path, height, base, bottom_radius, top_radius):
    """Traffic cone standing on the origin: a square base plate and a cone body with a flat top."""
    vertices, uvs, normals, faces = [], [], [], []

    def add_face(points, face_uvs, point_normals):
        first = len(vertices) + 1
        vertices.extend(points)
        uvs.extend(face_uvs)
        normals.extend(point_normals)
        faces.append(' '.join(f'{first + i}/{first + i}/{first + i}' for i in range(len(points))))

    # Base plate, all black (texture V above CONE_BASE_V).
    b, t = base / 2, CONE_BASE_HEIGHT
    black = (0.5, (1 + CONE_BASE_V) / 2)
    corners = [(-b, -b), (b, -b), (b, b), (-b, b)]
    add_face([(x, y, t) for x, y in corners], [black] * 4, [(0, 0, 1)] * 4)
    add_face([(x, y, 0) for x, y in reversed(corners)], [black] * 4, [(0, 0, -1)] * 4)
    for (x0, y0), (x1, y1) in zip(corners, corners[1:] + corners[:1]):
        n = (y1 - y0, x0 - x1, 0)
        length = math.hypot(*n[:2])
        add_face([(x0, y0, 0), (x1, y1, 0), (x1, y1, t), (x0, y0, t)], [black] * 4, [(n[0] / length, n[1] / length, 0)] * 4)

    # Body: V goes from CONE_BASE_V at the bottom to 0 at the top.
    slope = (bottom_radius - top_radius) / (height - t)
    nz = slope / math.hypot(1, slope)
    nr = 1 / math.hypot(1, slope)
    for i in range(CONE_SEGMENTS):
        a0, a1 = 2 * math.pi * i / CONE_SEGMENTS, 2 * math.pi * (i + 1) / CONE_SEGMENTS
        u0, u1 = i / CONE_SEGMENTS, (i + 1) / CONE_SEGMENTS
        points = [(bottom_radius * math.cos(a0), bottom_radius * math.sin(a0), t),
                  (bottom_radius * math.cos(a1), bottom_radius * math.sin(a1), t),
                  (top_radius * math.cos(a1), top_radius * math.sin(a1), height),
                  (top_radius * math.cos(a0), top_radius * math.sin(a0), height)]
        n0 = (nr * math.cos(a0), nr * math.sin(a0), nz)
        n1 = (nr * math.cos(a1), nr * math.sin(a1), nz)
        add_face(points, [(u0, CONE_BASE_V), (u1, CONE_BASE_V), (u1, 0.0), (u0, 0.0)], [n0, n1, n1, n0])
        add_face([(0, 0, height), points[3], points[2]], [(0.5, 0.0)] * 3, [(0, 0, 1)] * 3)

    lines = ['# Traffic cone, generated by gen_media.py']
    lines += ['v {:.5f} {:.5f} {:.5f}'.format(*v) for v in vertices]
    lines += ['vt {:.5f} {:.5f}'.format(u, 1 - v) for u, v in uvs]
    lines += ['vn {:.5f} {:.5f} {:.5f}'.format(*n) for n in normals]
    lines += ['f ' + f for f in faces]
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


# Flat boards (length, width, thickness, m): low and narrow enough for the robot
# to drive over them between its wheels (0.15 m apart, 3.5 cm under the chassis).
BOARDS = {
    'flat_board.obj': (0.5, 0.09, 0.018),
}
# Texture tile of the boards, m.
BOARD_TILE = 0.5


def write_board(path, length, width, thickness):
    """A box lying on the origin (z from 0 to 'thickness'), with metric texture coordinates on each face."""
    lx, ly = length / 2, width / 2
    faces_def = [  # normal, four corners counterclockwise seen from outside, the two face axes for UVs
        ((0, 0, 1), [(-lx, -ly, thickness), (lx, -ly, thickness), (lx, ly, thickness), (-lx, ly, thickness)], (0, 1)),
        ((0, 0, -1), [(-lx, ly, 0), (lx, ly, 0), (lx, -ly, 0), (-lx, -ly, 0)], (0, 1)),
        ((1, 0, 0), [(lx, -ly, 0), (lx, ly, 0), (lx, ly, thickness), (lx, -ly, thickness)], (1, 2)),
        ((-1, 0, 0), [(-lx, ly, 0), (-lx, -ly, 0), (-lx, -ly, thickness), (-lx, ly, thickness)], (1, 2)),
        ((0, 1, 0), [(lx, ly, 0), (-lx, ly, 0), (-lx, ly, thickness), (lx, ly, thickness)], (0, 2)),
        ((0, -1, 0), [(-lx, -ly, 0), (lx, -ly, 0), (lx, -ly, thickness), (-lx, -ly, thickness)], (0, 2)),
    ]
    lines = ['# Flat board, generated by gen_media.py']
    faces = []
    for i, (normal, corners, (a, b)) in enumerate(faces_def):
        lines += ['v {:.5f} {:.5f} {:.5f}'.format(*c) for c in corners]
        lines += ['vt {:.5f} {:.5f}'.format(c[a] / BOARD_TILE, c[b] / BOARD_TILE) for c in corners]
        lines.append('vn {:.1f} {:.1f} {:.1f}'.format(*normal))
        k = 4 * i
        faces.append(' '.join(f'{k + j + 1}/{k + j + 1}/{i + 1}' for j in range(4)))
    lines += ['f ' + f for f in faces]
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    media_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'media')

    textures_dir = os.path.join(media_dir, 'textures')
    os.makedirs(textures_dir, exist_ok=True)
    for name, generate in TEXTURES.items():
        path = os.path.join(textures_dir, name)
        image = generate()
        image.save(path, quality=88)
        print(f'{path}: {os.path.getsize(path) // 1024} KB')
        if name.startswith('marking_'):
            # One stripe period, which is the first line width of the texture.
            tile_path = path.replace('.png', '_tile.png')
            image.crop((0, 0, MARKING_SIZE[0], MARKING_SIZE[0])).save(tile_path)
            print(tile_path)

    meshes_dir = os.path.join(media_dir, 'meshes')
    os.makedirs(meshes_dir, exist_ok=True)
    for name, points in MITERS.items():
        path = os.path.join(meshes_dir, name)
        write_miter(path, name, points)
        print(path)

    for name, params in CONES.items():
        path = os.path.join(meshes_dir, name)
        write_cone(path, *params)
        print(path)

    for name, params in BOARDS.items():
        path = os.path.join(meshes_dir, name)
        write_board(path, *params)
        print(path)

    for params in OVERPASSES:
        path = os.path.join(meshes_dir, overpass_mesh_name(**params))
        write_overpass(path, **params)
        print(path)


if __name__ == '__main__':
    main()
