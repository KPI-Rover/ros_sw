"""
Box meshes with texture coordinates in metres, for textured walls and arches.

A box primitive maps a texture onto each whole face, so a wall texture made
for a wall 'segment' m long and WALL_TEXTURE_HEIGHT m high (walls.yaml) is
stretched or squashed on boxes of other sizes, e.g. short walls and arch
posts. These meshes keep the texture at its real size on every face, with
the texture height counted from the floor (a lintel shows the top of the
texture, as the wall around it does).

World generators make the meshes their walls and arches need at launch and
give the xacro world a dict {mesh_key(...): OBJ path} ('wall_meshes', see
structures.xacro); walls without a mesh fall back to box segments.
"""

import hashlib
import os

CACHE_DIR = os.path.join(os.path.expanduser('~'), '.cache', 'kpi_rover', 'meshes')
WALL_TEXTURE_HEIGHT = 0.5


def mesh_key(sx, sy, sz, material, z0=0.0):
    """Key of a box mesh, the same as structures.xacro builds it."""
    return '%.4fx%.4fx%.4f@%.4f/%s' % (sx, sy, sz, z0, material)


def box_mesh(sx, sy, sz, tile_u, tile_v, z0=0.0):
    """
    OBJ path of a box centered at the origin (sx along X, sy along Y, sz up)
    whose bottom is z0 above the floor, with texture coordinates in units of
    tile_u along the box and tile_v up; written to CACHE_DIR if missing.
    """
    name = 'box_' + hashlib.sha1(repr((round(sx, 4), round(sy, 4), round(sz, 4), round(tile_u, 4), round(tile_v, 4),
                                       round(z0, 4))).encode()).hexdigest()[:12] + '.obj'
    path = os.path.join(CACHE_DIR, name)
    if os.path.isfile(path):
        return path
    hx, hy, hz = sx / 2, sy / 2, sz / 2

    def v(z):
        return (z0 + z + hz) / tile_v

    # Each face: normal, corners counterclockwise seen from outside, their texture coordinates.
    faces = [
        ((0, -1, 0), [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, -hy, hz), (-hx, -hy, hz)],
         [((x + hx) / tile_u, v(z)) for x, _, z in [(-hx, 0, -hz), (hx, 0, -hz), (hx, 0, hz), (-hx, 0, hz)]]),
        ((0, 1, 0), [(hx, hy, -hz), (-hx, hy, -hz), (-hx, hy, hz), (hx, hy, hz)],
         [((hx - x) / tile_u, v(z)) for x, _, z in [(hx, 0, -hz), (-hx, 0, -hz), (-hx, 0, hz), (hx, 0, hz)]]),
        ((1, 0, 0), [(hx, -hy, -hz), (hx, hy, -hz), (hx, hy, hz), (hx, -hy, hz)],
         [((y + hy) / tile_u, v(z)) for _, y, z in [(0, -hy, -hz), (0, hy, -hz), (0, hy, hz), (0, -hy, hz)]]),
        ((-1, 0, 0), [(-hx, hy, -hz), (-hx, -hy, -hz), (-hx, -hy, hz), (-hx, hy, hz)],
         [((hy - y) / tile_u, v(z)) for _, y, z in [(0, hy, -hz), (0, -hy, -hz), (0, -hy, hz), (0, hy, hz)]]),
        ((0, 0, 1), [(-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (-hx, hy, hz)],
         [((x + hx) / tile_u, (y + hy) / tile_u) for x, y, _ in [(-hx, -hy, 0), (hx, -hy, 0), (hx, hy, 0), (-hx, hy, 0)]]),
        ((0, 0, -1), [(-hx, hy, -hz), (hx, hy, -hz), (hx, -hy, -hz), (-hx, -hy, -hz)],
         [((x + hx) / tile_u, (y + hy) / tile_u) for x, y, _ in [(-hx, hy, 0), (hx, hy, 0), (hx, -hy, 0), (-hx, -hy, 0)]]),
    ]
    lines = ['# Textured box, generated by worlds/lib/textured_box.py']
    elements = []
    for i, (normal, corners, uvs) in enumerate(faces):
        lines += ['v {:.5f} {:.5f} {:.5f}'.format(*c) for c in corners]
        lines += ['vt {:.5f} {:.5f}'.format(*uv) for uv in uvs]
        lines.append('vn {:.1f} {:.1f} {:.1f}'.format(*normal))
        k = 4 * i
        elements.append(' '.join(f'{k + j + 1}/{k + j + 1}/{i + 1}' for j in range(4)))
    lines += ['f ' + e for e in elements]
    os.makedirs(CACHE_DIR, exist_ok=True)
    tmp = path + f'.{os.getpid()}.tmp'
    with open(tmp, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    os.replace(tmp, path)
    return path


def wall_meshes(boxes, material, walls_cfg):
    """
    {mesh_key: OBJ path} for boxes [(sx, sy, sz, z0)] of a walls.yaml
    material; empty for an untextured material (a plain color needs none).
    """
    cfg = walls_cfg.get(material) or {}
    if not cfg.get('texture'):
        return {}
    return {mesh_key(sx, sy, sz, material, z0): box_mesh(sx, sy, sz, cfg['segment'], WALL_TEXTURE_HEIGHT, z0)
            for sx, sy, sz, z0 in boxes}


def perimeter_boxes(size_x, size_y, height=0.5, thickness=0.1):
    """Boxes of the perimeter walls of structures.xacro around a size_x x size_y area."""
    return [(size_x + 2 * thickness, thickness, height, 0.0), (size_y, thickness, height, 0.0)]
