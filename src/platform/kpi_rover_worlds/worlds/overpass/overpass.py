"""
Warehouse with a figure-eight marking and an overpass at its crossing.

The figure eight is two loops of radius r centered at (+-d, 0) and two
diagonals tangent to both, crossing at the origin at angles +-alpha. The
+alpha diagonal goes over the overpass, so two robots can drive the figure
eight at once without meeting. Start points a and b are at the outer points
of the loops, half a lap apart.
"""

import hashlib
import math
import os

from kpi_rover_worlds import scatter, sdf, textured_box

# Geometry, m: the warehouse inside, the figure eight (loop radius, distance
# from the crossing to the loop tangent points) and the overpass: the deck
# height leaves room under its bottom (5 cm lower) for the 0.345 m high robot;
# max_slope is the steepest ramp slope, degrees.
PARAMS = dict(size_x=15, size_y=8, marking_width=0.05, loop_radius=2.0, tangent_distance=4.5,
              height=0.45, deck_length=1.4, max_slope=12, rail_width=0.04,
              overpass_types={'wide': {'width': 0.7, 'rails': True}, 'narrow': {'width': 0.4, 'rails': False}})

# Free space kept on each side of the lane and around the overpass and start points, m.
LANE_MARGIN = 0.35
START_RADIUS = 0.6
# Road band: height above the floor (under the marking lines, 1 mm thick) and arc segment length, m.
ROAD_HEIGHT = 0.0005
ROAD_STEP = 0.1
RAIL_COLOR = (1.0, 0.8, 0.0)
RAIL_HEIGHT = 0.1
RAIL_PIECES = 16
DECK_THICKNESS = 0.05


def geometry(p):
    """
    Loop radius r, distance lt from the center to the tangent points, loop center distance d, angle alpha
    of the diagonals, and distance 'foot' from the center to the ends of the overpass ramps.
    """
    r, lt = p['loop_radius'], p['tangent_distance']
    foot = p['deck_length'] / 2 + p['height'] * math.pi / (2 * math.tan(math.radians(p['max_slope'])))
    return r, lt, math.hypot(lt, r), math.atan2(r, lt), foot


def figure_eight(p):
    """The figure eight on the floor: ('arc', cx, cy, r, a1, a2) and ('segment', x1, y1, x2, y2) pieces."""
    r, lt, d, alpha, foot = geometry(p)
    ca, sa = math.cos(alpha), math.sin(alpha)
    return [('arc', d, 0, r, -(math.pi / 2 + alpha), math.pi / 2 + alpha),
            ('arc', -d, 0, r, math.pi / 2 - alpha, 3 * math.pi / 2 + alpha),
            ('segment', -lt * ca, lt * sa, lt * ca, -lt * sa),
            ('segment', -lt * ca, -lt * sa, -foot * ca, -foot * sa),
            ('segment', foot * ca, foot * sa, lt * ca, lt * sa)]


def road_mesh(p, width, tile):
    """
    OBJ path of the road band along the figure eight on the floor, 'width'
    wide, with texture coordinates in units of 'tile' m; cached by its shape.
    """
    name = 'road_' + hashlib.sha1(repr((sorted(p.items(), key=str), width, tile)).encode()).hexdigest()[:12] + '.obj'
    path = os.path.join(textured_box.CACHE_DIR, name)
    if os.path.isfile(path):
        return path
    lines, faces, n = ['# Overpass road band, generated by overpass.py'], [], 0
    for piece in figure_eight(p):
        if piece[0] == 'arc':
            _, cx, cy, r, a1, a2 = piece
            k = max(2, int(abs(a2 - a1) * r / ROAD_STEP) + 1)
            points = [(cx + r * math.cos(a1 + (a2 - a1) * i / (k - 1)), cy + r * math.sin(a1 + (a2 - a1) * i / (k - 1)))
                      for i in range(k)]
        else:
            _, x1, y1, x2, y2 = piece
            points = [(x1, y1), (x2, y2)]
        along = 0.0
        for i, (x, y) in enumerate(points):
            ax, ay = points[min(i + 1, len(points) - 1)]
            bx, by = points[max(i - 1, 0)]
            dx, dy = ax - bx, ay - by
            length = math.hypot(dx, dy)
            nx, ny = -dy / length * width / 2, dx / length * width / 2
            if i:
                along += math.hypot(x - points[i - 1][0], y - points[i - 1][1])
            for side in (-1, 1):
                lines.append(f'v {x + side * nx:.4f} {y + side * ny:.4f} {ROAD_HEIGHT}')
                lines.append(f'vt {along / tile:.4f} {(side + 1) / 2 * width / tile:.4f}')
            if i:
                # 1-based vertices: right and left of the previous point, right and left of this one; counterclockwise from above.
                a, b, c, e = n + 2 * i - 1, n + 2 * i, n + 2 * i + 1, n + 2 * i + 2
                faces.append(f'f {a}/{a}/1 {c}/{c}/1 {e}/{e}/1 {b}/{b}/1')
        n += 2 * len(points)
    lines.append('vn 0 0 1')
    os.makedirs(textured_box.CACHE_DIR, exist_ok=True)
    tmp = path + f'.{os.getpid()}.tmp'    # several launches may write the same mesh at once
    with open(tmp, 'w') as f:
        f.write('\n'.join(lines + faces) + '\n')
    os.replace(tmp, path)
    return path


def shapes(overpass_type, objects_on_route=False):
    """Scatter area, keep-out shapes and obstacles; with objects_on_route the figure eight is not kept free."""
    p = PARAMS
    cfg = p['overpass_types'][overpass_type]
    r, lt, d, alpha, foot = geometry(p)
    ca, sa = math.cos(alpha), math.sin(alpha)
    lane = max(cfg['width'], 0.5) / 2 + LANE_MARGIN
    overpass = ('segment', -foot * ca, -foot * sa, foot * ca, foot * sa, cfg['width'] / 2)

    # The loops, the lower diagonal and the whole upper one.
    route = [piece + (lane,) for piece in figure_eight(p)[:3]]
    route.append(('segment', -lt * ca, -lt * sa, lt * ca, lt * sa, lane))
    # On the route, objects are obstacles; the overpass diagonal (its ramps) and the start points stay free anyway.
    keep_out = [route[3]] if objects_on_route else route
    keep_out += [('circle', d + r, 0, START_RADIUS), ('circle', -(d + r), 0, START_RADIUS)]
    area = (-p['size_x'] / 2, p['size_x'] / 2, -p['size_y'] / 2, p['size_y'] / 2)
    return area, keep_out, [overpass]


def overpass(parent, p, kind, yaw, offsets, style, surface):
    """A deck with a smooth ramp at each end, rails if kind['rails'], marking lines at 'offsets' from its axis."""
    height, deck, width, rail_width = p['height'], p['deck_length'], kind['width'], p['rail_width']
    ramp = height * math.pi / (2 * math.tan(math.radians(p['max_slope'])))
    half, rail_y = deck / 2, (width - rail_width) / 2
    cfg = sdf.FLOORS[surface]
    mesh = f"{sdf.MESHES_DIR}/overpass_w{width:g}_h{height:g}_d{deck:g}_t{DECK_THICKNESS:g}_s{p['max_slope']:g}.obj"
    link = sdf.static_model(parent, 'overpass', (0, 0, 0, 0, 0, yaw))
    collision = sdf.el(link, 'collision', name='body_collision')
    sdf.el(sdf.el(sdf.el(collision, 'geometry'), 'mesh'), 'uri', f'file://{mesh}')
    sdf.friction(collision, cfg['mu'])
    sdf.material(sdf.mesh_visual(link, 'body_visual', mesh), cfg['color'], cfg['texture'])

    def pieces(n):
        """(ramp, k, xa, za, xb, zb) of the n pieces of each ramp profile, from the ground to the deck."""
        for name, direction in (('ramp_in', -1), ('ramp_out', 1)):
            for k in range(n):
                yield (name, k, direction * (half + ramp - ramp * k / n), height * (1 - math.cos(math.pi * k / n)) / 2,
                       direction * (half + ramp - ramp * (k + 1) / n),
                       height * (1 - math.cos(math.pi * (k + 1) / n)) / 2)

    sides = (('left', rail_y), ('right', -rail_y))
    if kind['rails']:
        for side, y in sides:
            sdf.solid_box(link, f'deck_rail_{side}', 0, y, height + RAIL_HEIGHT / 2, deck, rail_width, RAIL_HEIGHT,
                          color=RAIL_COLOR)
        for name, k, xa, za, xb, zb in pieces(RAIL_PIECES):
            for side, y in sides:
                # Lengthened by half their height, so there are no gaps where the slope changes.
                sdf.solid_box(link, f'{name}_rail_{side}_{k}', (xa + xb) / 2, y, (za + zb) / 2 + RAIL_HEIGHT / 2,
                              math.hypot(xb - xa, zb - za) + RAIL_HEIGHT / 2, rail_width, RAIL_HEIGHT,
                              color=RAIL_COLOR, pitch=-math.atan2(zb - za, xb - xa))
    for i, offset in enumerate(offsets):
        sdf.marking_line(link, f'deck_marking_{i}', -half, offset, half, offset, style, height, height,
                         p['marking_width'])
    # Pieces about 1 width long, so the marking stays on the curved ramp.
    for name, k, xa, za, xb, zb in pieces(round(ramp / p['marking_width'])):
        for i, offset in enumerate(offsets):
            sdf.marking_line(link, f'{name}_marking_{k}_{i}', xa, offset, xb, offset, style, za, zb,
                             p['marking_width'], fine=True)


def build(args):
    p = PARAMS
    r, lt, d, alpha, foot = geometry(p)
    kind = p['overpass_types'][args['overpass']]
    width = p['marking_width']
    driveway = kind['width'] - (2 * p['rail_width'] if kind['rails'] else 0)
    # Lane edge lines lie inside the overpass driveway.
    offsets = [0] if args['lane'] == 'center' else [-(driveway - width) / 2, (driveway - width) / 2]

    root, world = sdf.world('overpass')
    sdf.floor(world, args['floor'], p['size_x'], p['size_y'])
    sdf.perimeter_walls(world, p['size_x'], p['size_y'], args['wall_material'])
    overpass(world, p, kind, alpha, offsets, args['marking'], args['overpass_surface'])
    if args['road'] != 'none':
        cfg = sdf.FLOORS[args['road']]
        link = sdf.static_model(world, 'figure_eight_road')
        sdf.material(sdf.mesh_visual(link, 'road', road_mesh(p, kind['width'], cfg['tile'])), cfg['color'],
                     cfg['texture'])
    link = sdf.static_model(world, 'figure_eight_marking')
    names = ('loop_right', 'loop_left', 'diagonal_lower', 'diagonal_upper_in', 'diagonal_upper_out')
    for name, (shape, *piece) in zip(names, figure_eight(p)):
        for i, offset in enumerate(offsets):
            if shape == 'arc':
                cx, cy, radius, a1, a2 = piece
                sdf.marking_arc(link, f'{name}_{i}', cx, cy, radius - offset, a1, a2, args['marking'], width)
            else:
                x1, y1, x2, y2 = piece
                length = math.hypot(x2 - x1, y2 - y1)
                nx, ny = -(y2 - y1) / length * offset, (x2 - x1) / length * offset
                sdf.marking_line(link, f'{name}_{i}', x1 + nx, y1 + ny, x2 + nx, y2 + ny, args['marking'],
                                 width=width)
    area, keep_out, obstacles = shapes(args['overpass'], args['objects_on_route'])
    for i, (kind_name, x, y, yaw) in enumerate(scatter.scatter_from_args(args, area, keep_out, obstacles, 'overpass')):
        sdf.scatter_object(world, f'{kind_name}_{i}', kind_name, x, y, yaw)
    # The right loop is driven counterclockwise and the left one clockwise, both heading +Y at the outer points.
    sdf.start_point(world, 'a', d + r, 0, math.pi / 2)
    sdf.start_point(world, 'b', -(d + r), 0, math.pi / 2)
    return root
